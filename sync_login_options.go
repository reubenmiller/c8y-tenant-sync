// loginItemPreferred is the item name of the preferred login mode
const loginItemPreferred = "preferred"

// loginOptionDefaults are the fields of a BASIC or OAUTH2_INTERNAL login
// option created by the sync (tenants normally have both already)
var loginOptionDefaults = map[string]map[string]any{
	LoginTypeBasic: {
		"type":                 LoginTypeBasic,
		"userManagementSource": "INTERNAL",
		"visibleOnLoginPage":   false,
	},
	LoginTypeOAISecure: {
		"type":                 LoginTypeOAISecure,
		"grantType":            "PASSWORD",
		"providerName":         "Cumulocity",
		"userManagementSource": "INTERNAL",
		"visibleOnLoginPage":   false,
	},
}

// sensitiveLoginOptionPaths hold the client secret: they are compared but
// their values are never shown
var sensitiveLoginOptionPaths = []string{
	"tokenRequest.body",
	"tokenRequest.headers.Authorization",
	"refreshRequest.body",
	"refreshRequest.headers.Authorization",
}

// replacedLoginOptionFields are generated as a whole: an update replaces
// them instead of merging them into the tenant's values, so fields which are
// no longer generated (such as an Authorization header with an old client
// secret) do not survive, and extra fields count as a change
var replacedLoginOptionFields = []string{
	"authorizationRequest",
	"tokenRequest",
	"refreshRequest",
	"logoutRequest",
	"signatureVerificationConfig",
}

// readOnlyLoginOptionFields are returned by GET but generated by the
// platform, so they are left out of POST and PUT. Settings the login option
// also carries, such as the password strength (enforceStrength,
// greenMinLength, strengthValidity) and the TFA strategy (tfaStrategy), are
// sent back as read, so an update never resets them.
var readOnlyLoginOptionFields = []string{
	"self",
	"id",
	"_type",
	"initRequest",
	"loginRedirectDomain",
	"tfaSupported",
}

// writableLoginOption returns the body to send for a login option
func writableLoginOption(option map[string]any) map[string]any {
	body := cloneMap(option)
	for _, field := range readOnlyLoginOptionFields {
		delete(body, field)
	}
	return body
}

// loginOptionState are the login options of a tenant by type (the first of
// each type)
type loginOptionState map[string]map[string]any

// visible reports whether the login option of the type exists and is shown
// on the login page
func (st loginOptionState) visible(loginType string) bool {
	option, ok := st[loginType]
	if !ok {
		return false
	}
	visible, _ := option["visibleOnLoginPage"].(bool)
	return visible
}

// preferredMode derives the preferred login mode from the visibility of the
// login options ("" when it cannot be told)
func (st loginOptionState) preferredMode() string {
	switch {
	case st.visible(LoginTypeSSO) && !st.visible(LoginTypeOAISecure) && !st.visible(LoginTypeBasic):
		return LoginModeSSO
	case st.visible(LoginTypeOAISecure):
		return LoginModeOAISecure
	case st.visible(LoginTypeBasic):
		return LoginModeBasic
	}
	return ""
}

// preferredVisibility is the visibility of the login options for a preferred
// login mode. The option of the mode is listed first: it is made visible
// before the others are hidden, so the login page always offers a login.
func preferredVisibility(mode string) []struct {
	loginType string
	visible   bool
} {
	type entry = struct {
		loginType string
		visible   bool
	}
	switch mode {
	case LoginModeBasic:
		return []entry{{LoginTypeBasic, true}, {LoginTypeOAISecure, false}}
	case LoginModeSSO:
		return []entry{{LoginTypeSSO, true}, {LoginTypeOAISecure, false}, {LoginTypeBasic, false}}
	default:
		return []entry{{LoginTypeOAISecure, true}, {LoginTypeBasic, false}}
	}
}

// SyncLoginOptions configures the login options of the tenant. It never
// deletes a login option, and it changes the preferred login mode last, only
// when the option of the new mode is configured and checked:
//
//   - the SSO login option is generated from the provider's discovery
//     document, which is checked first (issuer, endpoints, JWKS keys); a
//     failed check leaves the tenant unchanged and keeps the current mode
//   - the option of the new mode is made visible before the others are
//     hidden, and the result is read back; when it does not match, the
//     previous visibility is restored
//   - basic authentication restrictions which would block this tool, or the
//     login page when basic is preferred, are refused
func (s *Syncer) SyncLoginOptions(ctx context.Context, spec *LoginOptionsSpec) error {
	if spec == nil {
		return nil
	}

	// The SSO option is checked (also in dry-run mode) before anything is
	// written: its discovery document is public
	var sso *ssoLoginOption
	ssoOK := true
	if spec.SSO != nil {
		var err error
		sso, err = buildSSOLoginOption(ctx, spec.SSO, spec.Preferred)
		if err != nil {
			s.record(SectionLoginOptions, LoginTypeSSO, ActionFailed, "check sso login option", err)
			ssoOK = false
		}
	}

	basicDesired := basicLoginOptionBody(spec.Basic)
	oaiDesired, err := oaiSecureLoginOptionBody(spec.OAISecure)
	if err != nil {
		s.record(SectionLoginOptions, LoginTypeOAISecure, ActionFailed, "", err)
		oaiDesired = nil
	}

	if blocked := s.blockedUserAgents(spec.Basic); len(blocked) > 0 {
		s.record(SectionLoginOptions, LoginTypeBasic, ActionFailed, "", fmt.Errorf(
			"refusing to forbid the user agent(s) %s for basic authentication: this tool (User-Agent %q) would be blocked", strings.Join(blocked, ", "), s.userAgent()))
		basicDesired = nil
	}

	if s.DryRun && s.dryRunReader() == nil {
		// The tenant cannot be read (no session, or another tenant whose
		// credentials are only resolved in a real run): list the desired
		// settings without comparing them
		if basicDesired != nil {
			s.record(SectionLoginOptions, LoginTypeBasic, ActionPlanned, describeDesired(basicDesired), nil)
		}
		if oaiDesired != nil {
			s.record(SectionLoginOptions, LoginTypeOAISecure, ActionPlanned, describeDesired(oaiDesired), nil)
		}
		if sso != nil {
			s.record(SectionLoginOptions, LoginTypeSSO, ActionPlanned, sso.describe(), nil)
		}
		if spec.Preferred != "" {
			if spec.Preferred == LoginModeSSO && !ssoOK {
				s.record(SectionLoginOptions, loginItemPreferred, ActionFailed, "", fmt.Errorf("the preferred login mode would stay unchanged: the sso login option failed its check"))
			} else {
				s.record(SectionLoginOptions, loginItemPreferred, ActionPlanned, "set to "+spec.Preferred+" (after the other login options are configured; not compared with the tenant)", nil)
			}
		}
		return nil
	}

	state, err := s.loginOptions(ctx)
	if err != nil {
		s.record(SectionLoginOptions, "list", ActionFailed, "list login options", err)
		return nil
	}

	// Forbidding basic authentication for web browsers is applied after the
	// preferred login mode moved away from basic; lifting restrictions is
	// applied before, so basic can become the preferred mode
	basicForbids := basicDesired != nil && basicForbidsBrowsers(basicDesired)
	if basicDesired != nil && !basicForbids {
		s.ensureLoginOption(ctx, state, LoginTypeBasic, basicDesired)
	}

	if oaiDesired != nil {
		s.ensureLoginOption(ctx, state, LoginTypeOAISecure, oaiDesired)
	} else if _, found := state[LoginTypeOAISecure]; !found && spec.Preferred == LoginModeOAISecure {
		s.ensureLoginOption(ctx, state, LoginTypeOAISecure, map[string]any{})
	}

	// Hiding the SSO button while SSO is the only login on the login page
	// waits until the preferred mode moved away from SSO
	hideSSO := false
	if sso != nil {
		if visible, _ := sso.body["visibleOnLoginPage"].(bool); !visible && state.preferredMode() == LoginModeSSO {
			sso.body["visibleOnLoginPage"] = true
			hideSSO = true
		}
		if err := s.resolveSSOAccessMappings(ctx, spec.SSO, sso); err != nil {
			s.record(SectionLoginOptions, LoginTypeSSO, ActionFailed, "resolve access mappings", err)
			ssoOK = false
		} else if !s.ensureLoginOption(ctx, state, LoginTypeSSO, sso.body) {
			ssoOK = false
		}
	}

	if spec.Preferred != "" {
		s.setPreferredLogin(ctx, state, spec.Preferred, ssoOK)
	}

	if basicForbids {
		if state.preferredMode() == LoginModeBasic {
			s.record(SectionLoginOptions, LoginTypeBasic, ActionFailed, "", fmt.Errorf("refusing to forbid basic authentication for web browsers while basic is the preferred login mode (nobody could log in on the login page)"))
		} else {
			s.ensureLoginOption(ctx, state, LoginTypeBasic, basicDesired)
		}
	}

	if hideSSO {
		const item = LoginTypeSSO + " visibility"
		if state.preferredMode() == LoginModeSSO {
			s.record(SectionLoginOptions, item, ActionFailed, "", fmt.Errorf("kept the sso button visible: sso is the preferred login mode, set preferred to oaiSecure or basic first"))
		} else if err := s.setLoginOptionVisible(ctx, state, LoginTypeSSO, false); err != nil {
			s.record(SectionLoginOptions, item, ActionFailed, "hide the sso button", err)
		} else {
			s.record(SectionLoginOptions, item, s.writeAction(ActionUpdated), "visibleOnLoginPage: true → false", nil)
		}
	}
	return nil
}

// loginOptions reads the login options of the tenant
func (s *Syncer) loginOptions(ctx context.Context) (loginOptionState, error) {
	result := s.loginReadClient().LoginOptions.List(ctx, loginoptions.ListOptions{})
	if result.Err != nil {
		return nil, result.Err
	}
	state := loginOptionState{}
	for option, err := range result.Items() {
		if err != nil {
			return nil, err
		}
		var body map[string]any
		if err := json.Unmarshal(option.Bytes(), &body); err != nil {
			return nil, fmt.Errorf("invalid login option: %w", err)
		}
		loginType := strings.ToUpper(option.Type())
		if _, seen := state[loginType]; !seen {
			state[loginType] = body
		}
	}
	return state, nil
}

// ensureLoginOption creates the login option of the type, or updates it when
// the desired fields differ. The state is updated with the result. It reports
// whether the login option is in the desired state.
func (s *Syncer) ensureLoginOption(ctx context.Context, state loginOptionState, loginType string, desired map[string]any) bool {
	existing, found := state[loginType]
	if !found {
		body := deepMerge(cloneMap(loginOptionDefaults[loginType]), desired)
		body["type"] = loginType
		for key, value := range body {
			if value == nil {
				delete(body, key) // a field to remove does not apply to a new option
			}
		}
		if s.DryRun {
			state[loginType] = body
			s.record(SectionLoginOptions, loginType, ActionPlanned, "create: "+describeDesired(desired), nil)
			return true
		}
		result := s.Client.LoginOptions.Create(ctx, writableLoginOption(body))
		if result.Err != nil {
			s.record(SectionLoginOptions, loginType, ActionFailed, "create login option", result.Err)
			return false
		}
		// Keep the created option (with its id) for later updates
		var created map[string]any
		if err := json.Unmarshal(result.Data.Bytes(), &created); err == nil && created["id"] != nil {
			body = deepMerge(body, created)
		}
		state[loginType] = body
		s.record(SectionLoginOptions, loginType, ActionCreated, describeDesired(desired), nil)
		return true
	}

	changes := diffLoginOption(desired, existing, "")
	if len(changes) == 0 {
		s.record(SectionLoginOptions, loginType, ActionUnchanged, "", nil)
		return true
	}
	body := deepMerge(cloneMap(existing), desired)
	for _, field := range replacedLoginOptionFields {
		value, ok := desired[field]
		switch {
		case !ok:
		case value == nil && existing[field] == nil:
			delete(body, field) // nothing to remove
		default:
			body[field] = normalizeJSON(value) // null removes it
		}
	}
	if s.DryRun {
		state[loginType] = body
		s.record(SectionLoginOptions, loginType, ActionPlanned, strings.Join(changes, "; "), nil)
		return true
	}
	result := s.Client.LoginOptions.Update(ctx, loginOptionRef(existing, loginType), writableLoginOption(body))
	if result.Err != nil {
		s.record(SectionLoginOptions, loginType, ActionFailed, "update login option ("+strings.Join(changes, "; ")+")", result.Err)
		return false
	}
	state[loginType] = body
	s.record(SectionLoginOptions, loginType, ActionUpdated, strings.Join(changes, "; "), nil)
	return true
}

// setPreferredLogin switches the preferred login mode: the option of the
// mode is made visible on the login page first, then the others are hidden,
// and the result is read back. On any failure the previous visibility is
// restored, so the login page never ends up without a login.
func (s *Syncer) setPreferredLogin(ctx context.Context, state loginOptionState, mode string, ssoOK bool) {
	previous := state.preferredMode()
	targets := preferredVisibility(mode)

	if mode == LoginModeSSO && !ssoOK {
		s.record(SectionLoginOptions, loginItemPreferred, ActionFailed, "", fmt.Errorf("kept %s: the sso login option is not configured or failed its check", describeMode(previous)))
		return
	}
	if _, ok := state[targets[0].loginType]; !ok {
		s.record(SectionLoginOptions, loginItemPreferred, ActionFailed, "", fmt.Errorf("kept %s: the tenant has no %s login option", describeMode(previous), targets[0].loginType))
		return
	}
	if mode == LoginModeBasic && basicForbidsBrowsers(state[LoginTypeBasic]) {
		s.record(SectionLoginOptions, loginItemPreferred, ActionFailed, "", fmt.Errorf("kept %s: basic authentication is forbidden for web browsers, so nobody could log in on the login page", describeMode(previous)))
		return
	}

	var pending []struct {
		loginType string
		visible   bool
	}
	for _, target := range targets {
		if _, ok := state[target.loginType]; ok && state.visible(target.loginType) != target.visible {
			pending = append(pending, target)
		}
	}
	if len(pending) == 0 {
		s.record(SectionLoginOptions, loginItemPreferred, ActionUnchanged, mode, nil)
		return
	}

	// Remember the visibility to restore on failure
	original := map[string]bool{}
	for _, target := range pending {
		original[target.loginType] = state.visible(target.loginType)
	}
	var changed []string
	restore := func(cause error) {
		var restoreErrs []string
		for i := len(changed) - 1; i >= 0; i-- {
			loginType := changed[i]
			if err := s.setLoginOptionVisible(ctx, state, loginType, original[loginType]); err != nil {
				restoreErrs = append(restoreErrs, fmt.Sprintf("%s: %v", loginType, err))
			}
		}
		if len(restoreErrs) > 0 {
			cause = fmt.Errorf("%w; restoring the previous login mode failed (%s): check the login options of the tenant", cause, strings.Join(restoreErrs, "; "))
		} else {
			cause = fmt.Errorf("%w; restored %s", cause, describeMode(previous))
		}
		s.record(SectionLoginOptions, loginItemPreferred, ActionFailed, "", cause)
	}

	for _, target := range pending {
		if err := s.setLoginOptionVisible(ctx, state, target.loginType, target.visible); err != nil {
			restore(fmt.Errorf("set %s visibleOnLoginPage=%t: %w", target.loginType, target.visible, err))
			return
		}
		changed = append(changed, target.loginType)
	}

	if s.DryRun {
		var steps []string
		for _, target := range pending {
			steps = append(steps, fmt.Sprintf("%s visibleOnLoginPage=%t", target.loginType, target.visible))
		}
		s.record(SectionLoginOptions, loginItemPreferred, ActionPlanned, describeMode(previous)+" → "+mode+" ("+strings.Join(steps, ", ")+")", nil)
		return
	}

	// Read back what the login page will offer
	current, err := s.loginOptions(ctx)
	if err == nil {
		for _, target := range targets {
			if _, ok := current[target.loginType]; ok && current.visible(target.loginType) != target.visible {
				err = fmt.Errorf("%s visibleOnLoginPage is %t after the update, expected %t", target.loginType, current.visible(target.loginType), target.visible)
				break
			}
		}
		if err == nil && current.preferredMode() != mode {
			err = fmt.Errorf("the login mode is %s after the update", describeMode(current.preferredMode()))
		}
	}
	if err != nil {
		restore(fmt.Errorf("verify the login options: %w", err))
		return
	}
	s.record(SectionLoginOptions, loginItemPreferred, ActionUpdated, describeMode(previous)+" → "+mode, nil)
}

func (s *Syncer) setLoginOptionVisible(ctx context.Context, state loginOptionState, loginType string, visible bool) error {
	existing := state[loginType]
	body := cloneMap(existing)
	body["visibleOnLoginPage"] = visible
	if s.DryRun {
		state[loginType] = body
		return nil
	}
	result := s.Client.LoginOptions.Update(ctx, loginOptionRef(existing, loginType), writableLoginOption(body))
	if result.Err != nil {
		return result.Err
	}
	state[loginType] = body
	return nil
}

// dryRunReader is the client which reads the login options in dry-run mode:
// only for the current tenant (the credentials of other tenants are not
// resolved in a dry run), and only when a session is available
func (s *Syncer) dryRunReader() *api.Client {
	if s.DryRunReader == nil || (s.activeTarget != nil && !s.activeTarget.Current) {
		return nil
	}
	return s.DryRunReader
}

// loginReadClient is the client used to read the tenant's login options,
// global roles and applications (the read-only client in dry-run mode)
func (s *Syncer) loginReadClient() *api.Client {
	if s.DryRun {
		return s.dryRunReader()
	}
	return s.Client
}

// writeAction is the action recorded for a write: planned in dry-run mode
func (s *Syncer) writeAction(action Action) Action {
	if s.DryRun {
		return ActionPlanned
	}
	return action
}

func describeMode(mode string) string {
	if mode == "" {
		return "the current login mode"
	}
	return "login mode " + mode
}

// loginOptionRef is the id of the login option (its type when it has none)
func loginOptionRef(option map[string]any, loginType string) string {
	if id, ok := option["id"].(string); ok && id != "" {
		return id
	}
	return loginType
}

func basicForbidsBrowsers(option map[string]any) bool {
	restrictions, _ := option["authenticationRestrictions"].(map[string]any)
	return slices.Contains(stringList(restrictions["forbiddenClients"]), "WEB_BROWSERS")
}

// userAgent is the User-Agent header of this tool's requests
func (s *Syncer) userAgent() string {
	if s.Client != nil && s.Client.UserAgent != "" {
		return s.Client.UserAgent
	}
	return "go-client-v2"
}

// blockedUserAgents returns the forbidden user agents which match this
// tool's own User-Agent
func (s *Syncer) blockedUserAgents(spec *BasicLoginOptionSpec) []string {
	if spec == nil {
		return nil
	}
	own := strings.ToLower(s.userAgent())
	var blocked []string
	for _, agent := range spec.ForbiddenUserAgents {
		if strings.Contains(own, strings.ToLower(strings.TrimSpace(agent))) {
			blocked = append(blocked, agent)
		}
	}
	return blocked
}

// basicLoginOptionBody returns the desired fields of the BASIC login option
// (nil when nothing is declared)
func basicLoginOptionBody(spec *BasicLoginOptionSpec) map[string]any {
	if spec == nil {
		return nil
	}
	restrictions := map[string]any{}
	for name, list := range map[string][]string{
		"forbiddenClients":    spec.ForbiddenClients,
		"trustedUserAgents":   spec.TrustedUserAgents,
		"forbiddenUserAgents": spec.ForbiddenUserAgents,
	} {
		if list != nil {
			restrictions[name] = toAnyList(list)
		}
	}
	if len(restrictions) == 0 {
		return nil
	}
	return map[string]any{"authenticationRestrictions": restrictions}
}

// oaiSecureLoginOptionBody returns the desired fields of the OAUTH2_INTERNAL
// login option (nil when nothing is declared)
func oaiSecureLoginOptionBody(spec *OAISecureLoginSpec) (map[string]any, error) {
	if spec == nil || spec.Session == nil {
		return nil, nil
	}
	session := map[string]any{}
	if spec.Session.AbsoluteTimeout != "" {
		d, err := parseOptionalDuration(spec.Session.AbsoluteTimeout)
		if err != nil {
			return nil, fmt.Errorf("absoluteTimeout: %w", err)
		}
		session["absoluteTimeoutMillis"] = float64(d.Milliseconds())
	}
	if spec.Session.RenewalTimeout != "" {
		d, err := parseOptionalDuration(spec.Session.RenewalTimeout)
		if err != nil {
			return nil, fmt.Errorf("renewalTimeout: %w", err)
		}
		session["renewalTimeoutMillis"] = float64(d.Milliseconds())
	}
	if spec.Session.MaximumParallelSessions != nil {
		session["maximumNumberOfParallelSessions"] = float64(*spec.Session.MaximumParallelSessions)
	}
	if spec.Session.UserAgentValidationRequired != nil {
		session["userAgentValidationRequired"] = *spec.Session.UserAgentValidationRequired
	}
	if len(session) == 0 {
		return nil, nil
	}
	return map[string]any{"sessionConfiguration": session}, nil
}

// ssoLoginOption is the generated SSO login option
type ssoLoginOption struct {
	discoveryURL string
	provider     oidcProvider
	body         map[string]any
}

func (o *ssoLoginOption) describe() string {
	parts := []string{
		"from " + o.discoveryURL,
		"issuer " + o.provider.Issuer,
		"authorization " + o.provider.AuthorizationEndpoint,
		"token " + o.provider.TokenEndpoint,
		"jwks " + o.provider.JWKSURI,
	}
	if o.provider.EndSessionEndpoint != "" {
		parts = append(parts, "logout "+o.provider.EndSessionEndpoint)
	}
	if o.provider.clientSecretBasic() {
		parts = append(parts, "client secret in the Authorization header")
	} else {
		parts = append(parts, "client secret in the request body")
	}
	if visible, _ := o.body["visibleOnLoginPage"].(bool); visible {
		parts = append(parts, "visible on the login page")
	}
	return strings.Join(parts, ", ")
}

// buildSSOLoginOption checks the provider and generates the SSO login option.
// The access mapping rules reference global roles and applications by name; they
// are resolved to IDs by resolveSSOAccessMappings.
func buildSSOLoginOption(ctx context.Context, spec *SSOLoginSpec, preferred string) (*ssoLoginOption, error) {
	if strings.TrimSpace(spec.ClientSecret) == "" {
		return nil, fmt.Errorf("the client secret is empty")
	}
	provider, err := discoverOIDCProvider(ctx, spec.DiscoveryURL)
	if err != nil {
		return nil, err
	}

	scopes := spec.Scopes
	if len(scopes) == 0 {
		scopes = []string{"openid", "profile", "email"}
	}
	providerName := spec.ProviderName
	if providerName == "" {
		if u, err := url.Parse(provider.Issuer); err == nil && u.Hostname() != "" {
			providerName = u.Hostname()
		} else {
			providerName = "SSO"
		}
	}
	buttonName := spec.ButtonName
	if buttonName == "" {
		buttonName = "Log in with " + providerName
	}

	// The platform substitutes ${code}, ${refreshToken} and ${redirectUri};
	// the body is sent as is, so the values are encoded here
	tokenHeaders := map[string]any{
		"Content-Type": "application/x-www-form-urlencoded",
		"Accept":       "application/json",
	}
	clientParams := "&client_id=" + url.QueryEscape(spec.ClientID) + "&client_secret=" + url.QueryEscape(spec.ClientSecret)
	if provider.clientSecretBasic() {
		tokenHeaders["Authorization"] = clientSecretBasicHeader(spec.ClientID, spec.ClientSecret)
		clientParams = "&client_id=" + url.QueryEscape(spec.ClientID)
	}
	refreshHeaders := cloneMap(tokenHeaders)

	body := map[string]any{
		"type":               LoginTypeSSO,
		"grantType":          "AUTHORIZATION_CODE",
		"providerName":       providerName,
		"buttonName":         buttonName,
		"visibleOnLoginPage": spec.visible(preferred),
		"issuer":             provider.Issuer,
		"clientId":           spec.ClientID,
		"useIdToken":         spec.useIDToken(),
		"authorizationRequest": map[string]any{
			"method":    "GET",
			"operation": "REDIRECT",
			"url":       provider.AuthorizationEndpoint,
			"requestParams": map[string]any{
				"response_type": "code",
				"client_id":     spec.ClientID,
				"scope":         strings.Join(scopes, " "),
				"redirect_uri":  "${redirectUri}",
			},
		},
		"tokenRequest": map[string]any{
			"method":    "POST",
			"operation": "EXECUTE",
			"url":       provider.TokenEndpoint,
			"headers":   tokenHeaders,
			"body":      "grant_type=authorization_code&code=${code}&redirect_uri=${redirectUri}" + clientParams,
		},
		"refreshRequest": map[string]any{
			"method":    "POST",
			"operation": "EXECUTE",
			"url":       provider.TokenEndpoint,
			"headers":   refreshHeaders,
			"body":      "grant_type=refresh_token&refresh_token=${refreshToken}" + clientParams,
		},
		"signatureVerificationConfig": map[string]any{
			"jwks": map[string]any{"jwksUrl": provider.JWKSURI},
		},
		"userIdConfig": map[string]any{
			"jwtField":         firstNonEmpty(spec.UserIDClaim, "sub"),
			"useConstantValue": false,
		},
		"accessTokenToUserDataMapping": ssoUserDataMapping(spec.UserData),
	}
	// Without a logout endpoint, an earlier logoutRequest is removed (nil)
	body["logoutRequest"] = nil
	if provider.EndSessionEndpoint != "" {
		body["logoutRequest"] = map[string]any{
			"method":    "GET",
			"operation": "REDIRECT",
			"url":       provider.EndSessionEndpoint,
			"requestParams": map[string]any{
				"client_id":     spec.ClientID,
				"id_token_hint": "${id_token}",
			},
		}
	}
	if spec.Audience != "" {
		body["audience"] = spec.Audience
	}
	if spec.Template != "" {
		body["template"] = spec.Template
	}
	if spec.RedirectToPlatform != "" {
		body["redirectToPlatform"] = spec.RedirectToPlatform
	}
	if spec.Access != nil {
		mapFromIDToken := spec.useIDToken()
		if spec.Access.MapFromIDToken != nil {
			mapFromIDToken = *spec.Access.MapFromIDToken
		}
		body["onNewUser"] = map[string]any{
			"dynamicMapping": map[string]any{
				"configuration": map[string]any{
					"mapRolesOnlyForNewUser":           spec.Access.MapRolesOnlyForNewUser,
					"manageRolesOnlyFromAccessMapping": spec.Access.ManageRolesOnlyFromAccessMapping,
					"mapFromIdToken":                   mapFromIDToken,
				},
				// Filled in by resolveSSOAccessMappings
				"mappings": []any{},
			},
		}
	}
	if len(spec.Overrides) > 0 {
		body = deepMerge(body, normalizeJSON(spec.Overrides).(map[string]any))
	}
	return &ssoLoginOption{discoveryURL: spec.DiscoveryURL, provider: provider, body: body}, nil
}

// resolveSSOAccessMappings resolves the group and application names of the
// access mapping rules to IDs. A name which cannot be resolved fails the SSO
// login option (and so keeps the current preferred login mode).
func (s *Syncer) resolveSSOAccessMappings(ctx context.Context, spec *SSOLoginSpec, option *ssoLoginOption) error {
	if spec.Access == nil {
		return nil
	}
	groupIDs := map[string]int{}
	appIDs := map[string]int{}
	var mappings []any
	for i, rule := range spec.Access.Rules {
		var groups, apps []any
		for _, name := range rule.GlobalRoles {
			id, ok := groupIDs[name]
			if !ok {
				group := s.loginReadClient().UserGroups.GetByName(ctx, usergroups.GetByNameOptions{GroupName: name})
				if group.Err != nil {
					return fmt.Errorf("rules[%d]: global role %q: %w", i, name, group.Err)
				}
				var err error
				if id, err = strconv.Atoi(group.Data.ID()); err != nil {
					return fmt.Errorf("rules[%d]: global role %q: invalid id %q", i, name, group.Data.ID())
				}
				groupIDs[name] = id
			}
			groups = append(groups, float64(id))
		}
		for _, name := range rule.Applications {
			id, ok := appIDs[name]
			if !ok {
				apps := s.loginReadClient().Applications
				resolved, err := apps.ResolveID(ctx, apps.ByName(name, ""), nil)
				if err != nil {
					return fmt.Errorf("rules[%d]: application %q: %w", i, name, err)
				}
				if id, err = strconv.Atoi(resolved); err != nil {
					return fmt.Errorf("rules[%d]: application %q: invalid id %q", i, name, resolved)
				}
				appIDs[name] = id
			}
			apps = append(apps, float64(id))
		}
		operator := "AND"
		if rule.Match == "any" {
			operator = "OR"
		}
		var predicates []any
		for _, cond := range rule.When {
			predicates = append(predicates, map[string]any{
				"parameterPath": cond.Claim,
				"operator":      firstNonEmpty(cond.Operator, "EQ"),
				"value":         cond.Value,
			})
		}
		mapping := map[string]any{
			"when": map[string]any{
				"operator":        operator,
				"childPredicates": predicates,
			},
			"thenGroups":       nonNilList(groups),
			"thenApplications": nonNilList(apps),
		}
		mappings = append(mappings, mapping)
	}
	// overrides could have replaced the generated onNewUser.dynamicMapping
	onNewUser, ok := option.body["onNewUser"].(map[string]any)
	if !ok {
		return fmt.Errorf("overrides replace onNewUser, which accessMappings needs: remove onNewUser from overrides")
	}
	dynamic, ok := onNewUser["dynamicMapping"].(map[string]any)
	if !ok {
		return fmt.Errorf("overrides replace onNewUser.dynamicMapping, which accessMappings needs: remove it from overrides")
	}
	dynamic["mappings"] = nonNilList(mappings)
	return nil
}

func ssoUserDataMapping(spec *SSOUserDataSpec) map[string]any {
	data := SSOUserDataSpec{}
	if spec != nil {
		data = *spec
	}
	mapping := map[string]any{
		"emailClaimName":     firstNonEmpty(data.Email, "email"),
		"firstNameClaimName": firstNonEmpty(data.FirstName, "given_name"),
		"lastNameClaimName":  firstNonEmpty(data.LastName, "family_name"),
	}
	if data.PhoneNumber != "" {
		mapping["phoneNumberClaimName"] = data.PhoneNumber
	}
	return mapping
}

// clientSecretBasicHeader is the client_secret_basic Authorization header
// (RFC 6749 section 2.3.1: the client ID and secret are form encoded first)
func clientSecretBasicHeader(clientID, secret string) string {
	credentials := url.QueryEscape(clientID) + ":" + url.QueryEscape(secret)
	return "Basic " + base64.StdEncoding.EncodeToString([]byte(credentials))
}

// ssoSecretForms are the forms in which the client secret appears in the
// login option, so all of them can be masked in the output
func ssoSecretForms(spec *SSOLoginSpec) []string {
	if spec == nil || spec.ClientSecret == "" {
		return nil
	}
	header := clientSecretBasicHeader(spec.ClientID, spec.ClientSecret)
	return []string{spec.ClientSecret, url.QueryEscape(spec.ClientSecret), header, strings.TrimPrefix(header, "Basic ")}
}

// diffLoginOption lists the desired fields which differ from the existing
// login option. Objects are compared field by field (fields which are not
// desired are ignored); lists element by element.
func diffLoginOption(desired any, existing any, path string) []string {
	if desiredMap, ok := desired.(map[string]any); ok {
		existingMap, _ := existing.(map[string]any)
		keys := make([]string, 0, len(desiredMap))
		for key := range desiredMap {
			keys = append(keys, key)
		}
		sort.Strings(keys)
		var changes []string
		for _, key := range keys {
			childPath := key
			if path != "" {
				childPath = path + "." + key
			}
			changes = append(changes, diffLoginOption(desiredMap[key], existingMap[key], childPath)...)
		}
		if isReplacedLoginOptionPath(path) {
			// Fields of a replaced object which are no longer generated
			var extra []string
			for key := range existingMap {
				if _, ok := desiredMap[key]; !ok {
					childPath := path + "." + key
					if slices.Contains(sensitiveLoginOptionPaths, childPath) {
						extra = append(extra, childPath+" removed")
					} else {
						extra = append(extra, fmt.Sprintf("%s: %s → (unset)", childPath, describeValue(existingMap[key])))
					}
				}
			}
			sort.Strings(extra)
			changes = append(changes, extra...)
		}
		return changes
	}
	if subsetEqual(desired, existing) {
		return nil
	}
	if slices.Contains(sensitiveLoginOptionPaths, path) {
		return []string{path + " changed"}
	}
	return []string{fmt.Sprintf("%s: %s → %s", path, describeValue(existing), describeValue(desired))}
}

// isReplacedLoginOptionPath reports whether the path is (inside) a field
// which is replaced as a whole
func isReplacedLoginOptionPath(path string) bool {
	for _, field := range replacedLoginOptionFields {
		if path == field || strings.HasPrefix(path, field+".") {
			return true
		}
	}
	return false
}

// subsetEqual reports whether existing has the desired value: objects need
// the desired fields only, lists the same length with matching elements. A
// single string matches a list with only that string (the API returns some
// lists as a string).
func subsetEqual(desired, existing any) bool {
	desired = normalizeJSON(desired)
	existing = normalizeJSON(existing)
	switch d := desired.(type) {
	case map[string]any:
		e, ok := existing.(map[string]any)
		if !ok {
			return false
		}
		for key, value := range d {
			if !subsetEqual(value, e[key]) {
				return false
			}
		}
		return true
	case []any:
		if s, ok := existing.(string); ok {
			existing = []any{s}
		}
		if existing == nil {
			return len(d) == 0
		}
		e, ok := existing.([]any)
		if !ok || len(e) != len(d) {
			return false
		}
		for i := range d {
			if !subsetEqual(d[i], e[i]) {
				return false
			}
		}
		return true
	}
	return reflect.DeepEqual(desired, existing)
}

// normalizeJSON converts a value to its JSON form (maps, []any, float64,
// strings and booleans)
func normalizeJSON(value any) any {
	raw, err := json.Marshal(value)
	if err != nil {
		return value
	}
	var out any
	if err := json.Unmarshal(raw, &out); err != nil {
		return value
	}
	return out
}

func describeValue(value any) string {
	if value == nil {
		return "(unset)"
	}
	raw, err := json.Marshal(value)
	if err != nil {
		return fmt.Sprint(value)
	}
	return string(raw)
}

// describeDesired lists the desired fields (sensitive ones by name only)
func describeDesired(desired map[string]any) string {
	var parts []string
	var walk func(value any, path string)
	walk = func(value any, path string) {
		if m, ok := value.(map[string]any); ok {
			keys := make([]string, 0, len(m))
			for key := range m {
				keys = append(keys, key)
			}
			sort.Strings(keys)
			for _, key := range keys {
				childPath := key
				if path != "" {
					childPath = path + "." + key
				}
				walk(m[key], childPath)
			}
			return
		}
		if value == nil {
			return // a field to remove
		}
		if slices.Contains(sensitiveLoginOptionPaths, path) {
			parts = append(parts, path+"=***")
			return
		}
		parts = append(parts, path+"="+describeValue(value))
	}
	walk(desired, "")
	return strings.Join(parts, ", ")
}

// deepMerge merges over into base (objects recursively, other values
// replaced) and returns base
func deepMerge(base, over map[string]any) map[string]any {
	if base == nil {
		base = map[string]any{}
	}
	for key, value := range over {
		if overMap, ok := value.(map[string]any); ok {
			if baseMap, ok := base[key].(map[string]any); ok {
				base[key] = deepMerge(cloneMap(baseMap), overMap)
				continue
			}
			base[key] = deepMerge(map[string]any{}, overMap)
			continue
		}
		base[key] = value
	}
	return base
}

// cloneMap returns a deep copy of a JSON object
func cloneMap(m map[string]any) map[string]any {
	if m == nil {
		return map[string]any{}
	}
	out, ok := normalizeJSON(m).(map[string]any)
	if !ok {
		return map[string]any{}
	}
	return out
}

func stringList(value any) []string {
	switch v := value.(type) {
	case string:
		return []string{v}
	case []any:
		var out []string
		for _, item := range v {
			if s, ok := item.(string); ok {
				out = append(out, s)
			}
		}
		return out
	case []string:
		return v
	}
	return nil
}

func toAnyList(values []string) []any {
	out := make([]any, 0, len(values))
	for _, value := range values {
		out = append(out, value)
	}
	return out
}

func nonNilList(values []any) []any {
	if values == nil {
		return []any{}
	}
	return values
}

func firstNonEmpty(values ...string) string {
	for _, value := range values {
		if value != "" {
			return value
		}
	}
	return ""
}
